import { expect, test, type Page } from "@playwright/test";
import assert from "node:assert/strict";

const enabled = process.env.RUN_LOCAL_WORKFLOW_E2E === "true";
test.skip(!enabled, "Requires the explicitly guarded disposable local workflow fixture runner.");
test.use({ trace: "off", screenshot: "off", video: "off" });
test.describe.configure({ retries: 0 }); // The seeded handover changes state and cannot safely be replayed.

test("fictional Generator to Receiver inspection and verified receipt", async ({ browser }) => {
  test.setTimeout(180_000);
  const password = process.env.WORKFLOW_TEST_PASSWORD;
  assert(password, "Use the isolated workflow fixture runner, not a shared or production server.");
  async function login(role: string): Promise<Page> {
    const context = await browser.newContext({ timezoneId: "UTC", viewport: { width: 390, height: 844 } });
    const page = await context.newPage();
    await page.goto("http://localhost:3000/login");
    await page.getByLabel("Email address").fill(`${role}@example.test`);
    await page.getByLabel("Password", { exact: true }).fill(password!);
    await page.getByRole("button", { name: /sign in/i }).click();
    await expect(page).toHaveURL(/\/(?:app|generator|receiver|helper|admin)(?:\?|$)/, { timeout: 30_000 });
    return page;
  }
  const generator = await login("generator");
  const receiver = await login("receiver");
  const helper1 = await login("helper1");
  const helper2 = await login("helper2");
  const admin = await login("admin");
  await generator.goto("http://localhost:3000/app/listings/new");
  const localTime = (value: number) => new Date(value).toISOString().slice(0, 19);
  const now = Date.now();
  const pickupFrom = now + 35_000;
  await generator.getByLabel("Food name").fill("Fictional browser produce");
  await generator.getByLabel("Category").fill("produce");
  await generator.getByLabel("Quantity").fill("12");
  await generator.getByLabel("Ingredients").fill("Fictional ingredients");
  await generator.getByLabel("Prepared at").fill(localTime(now - 600_000));
  await generator.getByLabel("Use-by / best-before").fill(localTime(now + 7_200_000));
  await generator.getByLabel("Collection from").fill(localTime(pickupFrom));
  await generator.getByLabel("Collect by").fill(localTime(now + 3_600_000));
  await generator.getByLabel("Storage / handling instructions").fill("Fictional handling");
  await generator.getByLabel("Pickup address").fill("Fictional pickup address");
  await generator.getByRole("checkbox", { name: /information above is truthful/i }).check();
  const listingResponse = generator.waitForResponse((response) => response.url().endsWith("/api/donations") && response.request().method() === "POST");
  await generator.getByRole("button", { name: /save listing and match/i }).click();
  const listing = await listingResponse;
  expect(listing.status()).toBe(201);
  const { id: donationId } = await listing.json() as { id: string };
  await receiver.goto("http://localhost:3000/app/offers");
  await receiver.getByRole("link", { name: /review offer/i }).click();
  const offerResponse = receiver.waitForResponse((response) => /\/api\/offers\/[^/]+$/.test(new URL(response.url()).pathname) && response.request().method() === "POST");
  await receiver.getByRole("button", { name: /accept offer/i }).click();
  const offer = await offerResponse;
  expect(offer.status()).toBe(200);
  const { deliveryJobId: jobId } = await offer.json() as { deliveryJobId: string };
  assert(jobId);
  const jobUrl = `http://localhost:3000/app/deliveries/${jobId}`;
  await Promise.all([helper1.goto(jobUrl), helper2.goto(jobUrl)]);
  const claims = await Promise.all([helper1, helper2].map(async (page) => {
    const response = page.waitForResponse((item) => item.url().endsWith(`/api/jobs/${jobId}/claim`) && item.request().method() === "POST");
    await page.getByRole("button", { name: /claim delivery/i }).click();
    return (await response).status();
  }));
  expect(claims.filter((status) => status === 200)).toHaveLength(1);
  expect(claims.filter((status) => status === 404 || status === 409)).toHaveLength(1);
  const helper = claims[0] === 200 ? helper1 : helper2;
  const otherHelper = helper === helper1 ? helper2 : helper1;
  await helper.goto(jobUrl);
  await new Promise((resolve) => setTimeout(resolve, Math.max(0, pickupFrom - Date.now()) + 100));
  await helper.getByLabel("Collection condition").fill("Fictional packaging observation");
  await helper.getByRole("button", { name: /confirm collection/i }).click();
  await expect(helper.getByRole("status")).toContainText(/collection was recorded/i);
  await receiver.goto(jobUrl);
  await expect(receiver.getByRole("button", { name: /show delivery code/i })).toHaveCount(0);
  const beforeArrival = await receiver.evaluate(async (id) => (await fetch(`/api/jobs/${id}/code`, { method: "POST" })).status, jobId);
  expect(beforeArrival).toBe(409);
  await helper.reload();
  await helper.getByRole("button", { name: /report physical arrival/i }).click();
  await expect(helper.getByRole("status")).toContainText(/arrival reported/i);
  await receiver.reload();
  await expect(receiver.getByRole("button", { name: /show delivery code/i })).toHaveCount(0);
  await receiver.getByLabel("Acceptance check observations").fill("Fictional inspection completed");
  await receiver.getByRole("checkbox", { name: /physically arrived/i }).check();
  await receiver.getByRole("button", { name: /record checks and acceptance/i }).click();
  await expect(receiver.getByRole("status")).toContainText(/acceptance and observations were recorded/i);
  await receiver.reload();
  const otherCodeStatus = await otherHelper.evaluate(async (id) => (await fetch(`/api/jobs/${id}/code`, { method: "POST" })).status, jobId);
  expect([403, 404]).toContain(otherCodeStatus);
  const generatorCodeStatus = await generator.evaluate(async (id) => (await fetch(`/api/jobs/${id}/code`, { method: "POST" })).status, jobId);
  expect(generatorCodeStatus).toBe(403);
  await receiver.getByRole("button", { name: /show delivery code/i }).click();
  const code = (await receiver.locator(".otp-display").innerText()).replace(/\D/g, "");
  assert.equal(/^\d{6}$/.test(code), true, "Receiver code must be six digits.");
  await helper.reload();
  const wrongCode = code === "000000" ? "000001" : "000000";
  await helper.getByLabel("Receiver's six-digit code").fill(wrongCode);
  await helper.getByRole("button", { name: /verify delivery/i }).click();
  await expect(helper.locator(".auth-error[role=alert]")).toContainText("4 attempts remain");
  await helper.getByLabel("Receiver's six-digit code").fill(code);
  await helper.getByRole("button", { name: /verify delivery/i }).click();
  await expect(helper.getByRole("status")).toContainText(/delivery verified/i);
  await generator.goto(`http://localhost:3000/app/listings/${donationId}`);
  await expect(generator.getByText(/receipt AL-/i).first()).toBeVisible();
  await receiver.goto(jobUrl);
  await expect(receiver.getByText(/receipt AL-/i).first()).toBeVisible();
  await admin.goto(jobUrl);
  await expect(admin.getByText(/receipt AL-/i).first()).toBeVisible();
  const impact = await (await receiver.request.get("http://localhost:3000/api/public/impact")).json() as { metrics: { verifiedDeliveries: number; verifiedServings: number } };
  expect(impact.metrics.verifiedDeliveries).toBe(1);
  expect(impact.metrics.verifiedServings).toBe(12);
});
